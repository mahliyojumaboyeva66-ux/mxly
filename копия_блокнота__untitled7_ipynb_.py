def make_dataset(x, y, optimized=True, training=False):

    ds = tf.data.Dataset.from_tensor_slices((x, y))

    if optimized:
        ds = ds.cache()

    if training:
        ds = ds.shuffle(
            buffer_size=len(y),
            seed=42,
            reshuffle_each_iteration=True
        )

    ds = ds.batch(BATCH_SIZE)

    if optimized:
        ds = ds.prefetch(tf.data.AUTOTUNE)

    return ds


