def build_model():

    inputs = {}
    embedding_outputs = []

    # Kategorik tarmoq
    for col in categorical_cols:

        inp = tf.keras.Input(
            shape=(1,),
            dtype=tf.string,
            name=col
        )

        inputs[col] = inp

        encoded = lookup_layers[col](inp)

        vocab_size = lookup_layers[col].vocabulary_size()

        embedding_dim = min(
            16,
            max(4, int(np.ceil(np.sqrt(vocab_size))))
        )

        embedding = tf.keras.layers.Embedding(
            input_dim=vocab_size,
            output_dim=embedding_dim
        )(encoded)

        embedding = tf.keras.layers.Flatten()(embedding)

        embedding_outputs.append(embedding)

    categorical_features = tf.keras.layers.Concatenate()(
        embedding_outputs
    )

    # Sonli tarmoq
    numeric_input = tf.keras.Input(
        shape=(len(numeric_cols),),
        dtype=tf.float32,
        name="numeric_features"
    )

    inputs["numeric_features"] = numeric_input

    numeric_features = normalizer(numeric_input)

    # Ikki tarmoqni birlashtirish
    combined = tf.keras.layers.Concatenate()([
        categorical_features,
        numeric_features
    ])

    x = tf.keras.layers.Dense(128, activation="relu")(combined)
    x = tf.keras.layers.BatchNormalization()(x)
    x = tf.keras.layers.Dropout(0.3)(x)

    x = tf.keras.layers.Dense(64, activation="relu")(x)
    x = tf.keras.layers.Dropout(0.2)(x)

    output = tf.keras.layers.Dense(
        1,
        activation="sigmoid"
    )(x)

    return tf.keras.Model(inputs, output)


