val_accuracy_metric = tf.keras.metrics.BinaryAccuracy()


@tf.function
def train_step(x_batch, y_batch):

    with tf.GradientTape() as tape:

        predictions = model_tape(
            x_batch,
            training=True
        )

        loss = loss_function(
            y_batch,
            predictions
        )

    gradients = tape.gradient(
        loss,
        model_tape.trainable_variables
    )

    optimizer.apply_gradients(
        zip(gradients, model_tape.trainable_variables)
    )

    train_loss_metric.update_state(loss)

    train_accuracy_metric.update_state(
        y_batch,
        predictions
    )


@tf.function
def validation_step(x_batch, y_batch):

    predictions = model_tape(
        x_batch,
        training=False
    )

    loss = loss_function(y_batch, predictions)

    val_loss_metric.update_state(loss)

    val_accuracy_metric.update_state(
        y_batch,
        predictions
    )


# O'qitish
